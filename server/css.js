// CSS generator: validates a theme object and builds a stylesheet from it.
const FONTS = {
  system: 'system-ui, -apple-system, "Segoe UI", sans-serif',
  inter: '"Inter", system-ui, sans-serif',
  serif: 'Georgia, "Times New Roman", serif',
  mono: 'ui-monospace, Menlo, Consolas, monospace',
  rounded: '"Trebuchet MS", "Segoe UI", sans-serif',
};
const DENSITY = { compact: 12, comfortable: 18, spacious: 26 };
const SHADOWS = ['none', '0 1px 3px rgba(0,0,0,.35)', '0 6px 18px rgba(0,0,0,.4)', '0 12px 32px rgba(0,0,0,.5)'];
const COLOR_KEYS = ['bg', 'surface', 'border', 'text', 'muted', 'primary', 'accent'];

const base = { fontFamily: 'system', fontSize: 14, radius: 10, sidebarWidth: 240, shadow: 1, density: 'comfortable', comments: true, minify: false };
const PRESETS = {
  darkblue: { ...base, name: 'Dark Blue', bg: '#0a1628', surface: '#0f2040', border: '#1e3a66', text: '#e6efff', muted: '#8aa4cc', primary: '#3b82f6', accent: '#22d3ee' },
  midnight: { ...base, name: 'Midnight', bg: '#050b1a', surface: '#0b1530', border: '#19275a', text: '#dfe7ff', muted: '#7f8fc2', primary: '#6366f1', accent: '#a78bfa', radius: 6, density: 'compact', shadow: 2 },
  ocean: { ...base, name: 'Ocean', bg: '#06202b', surface: '#0a3042', border: '#14566f', text: '#e3f6ff', muted: '#86b7cc', primary: '#0ea5e9', accent: '#2dd4bf', radius: 14, fontFamily: 'rounded', fontSize: 15, sidebarWidth: 260 },
  slate: { ...base, name: 'Slate Blue', bg: '#0f172a', surface: '#1e293b', border: '#334155', text: '#f1f5f9', muted: '#94a3b8', primary: '#38bdf8', accent: '#fbbf24', radius: 8, fontFamily: 'inter' },
};

const bad = (msg) => Object.assign(new Error(msg), { status: 400 });
const intIn = (v, min, max, label) => {
  if (!Number.isInteger(v) || v < min || v > max) throw bad(`${label} must be a whole number from ${min} to ${max}`);
  return v;
};

function validate(t) {
  if (!t || typeof t !== 'object') throw bad('theme must be an object');
  const out = { name: String(t.name || 'Custom').slice(0, 30) };
  for (const k of COLOR_KEYS) {
    if (typeof t[k] !== 'string' || !/^#[0-9a-f]{6}$/i.test(t[k])) throw bad(`${k} must be a hex colour like #0a1628`);
    out[k] = t[k].toLowerCase();
  }
  if (!FONTS[t.fontFamily]) throw bad(`fontFamily must be one of: ${Object.keys(FONTS).join(', ')}`);
  if (!DENSITY[t.density]) throw bad(`density must be one of: ${Object.keys(DENSITY).join(', ')}`);
  out.fontFamily = t.fontFamily;
  out.density = t.density;
  out.fontSize = intIn(t.fontSize, 12, 18, 'fontSize');
  out.radius = intIn(t.radius, 0, 24, 'radius');
  out.sidebarWidth = intIn(t.sidebarWidth, 200, 320, 'sidebarWidth');
  out.shadow = intIn(t.shadow, 0, 3, 'shadow');
  out.comments = t.comments !== false;
  out.minify = t.minify === true;
  return out;
}

function build(input) {
  const t = validate(input);
  const c = (s) => (t.comments ? `/* ${s} */\n` : '');
  let css =
`${c(`Theme: ${t.name} - generated by Admin Dashboard CSS Generator`)}:root {
  --bg: ${t.bg};
  --surface: ${t.surface};
  --border: ${t.border};
  --text: ${t.text};
  --muted: ${t.muted};
  --primary: ${t.primary};
  --accent: ${t.accent};
  --font: ${FONTS[t.fontFamily]};
  --font-size: ${t.fontSize}px;
  --radius: ${t.radius}px;
  --sidebar-w: ${t.sidebarWidth}px;
  --gap: ${DENSITY[t.density]}px;
  --shadow: ${SHADOWS[t.shadow]};
}

${c('Base')}* { box-sizing: border-box; }
body { margin: 0; background: var(--bg); color: var(--text); font-family: var(--font); font-size: var(--font-size); }
a { color: var(--accent); }

${c('Layout')}.sidebar { width: var(--sidebar-w); background: var(--surface); border-right: 1px solid var(--border); }
.card { background: var(--surface); border: 1px solid var(--border); border-radius: var(--radius); padding: var(--gap); box-shadow: var(--shadow); }

${c('Controls')}.btn { background: var(--primary); color: #fff; border: 0; border-radius: var(--radius); padding: calc(var(--gap) * .5) var(--gap); font: inherit; cursor: pointer; }
.btn:hover { filter: brightness(1.12); }
.btn-ghost { background: transparent; color: var(--text); border: 1px solid var(--border); }
input, select { background: var(--bg); color: var(--text); border: 1px solid var(--border); border-radius: calc(var(--radius) * .6); padding: calc(var(--gap) * .4) calc(var(--gap) * .6); font: inherit; }
input:focus, select:focus { outline: 2px solid var(--primary); outline-offset: 1px; }

${c('Tables and badges')}.table { width: 100%; border-collapse: collapse; }
.table th { color: var(--muted); font-weight: 600; text-align: left; }
.table th, .table td { padding: calc(var(--gap) * .5) var(--gap); border-bottom: 1px solid var(--border); }
.badge { background: color-mix(in srgb, var(--accent) 18%, transparent); color: var(--accent); border-radius: 999px; padding: 2px 10px; }
`;
  if (t.minify) css = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/\s*([{};:,])\s*/g, '$1').trim();
  return css;
}

module.exports = { build, validate, PRESETS, FONTS };
